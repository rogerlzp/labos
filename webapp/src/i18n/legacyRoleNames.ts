/**
 * 老数据里的**中文角色名** → 中性 code 的反向映射表（P-13）。
 *
 * <p><b>为什么需要这张表</b>：网关自动名在 2026-11-10 之前是**硬编码中文**
 * （设计器里写死「异或分叉 / 异或汇合 / 并行分叉 / 并行汇合」，与界面语种无关）。
 * 改成中性 code 之后，新数据存的是 `XOR_MERGE` 这类与语种无关的 code，
 * 界面渲染时再映射成本地化文案 —— 但**库里已有的中文名不在映射表里**，
 * 英文界面下就仍原样显示中文。
 *
 * <p><b>为什么不跑数据迁移</b>：老名字**可能是用户手起的自定义名**
 * （例如库里就有网关叫「分支」「B还要再来吗」）。跑迁移把中文名批量转成 code，
 * 就无法区分「自动生成的角色名」与「用户恰好写了同样字的自定义名」——
 * 后者被转成 code 会**丢掉用户自己的命名语义**。所以选**显示层映射**：
 * 库里的数据一个字都不动，只在读出来渲染时做一次反查。
 *
 * <p><b>口径</b>：只认**精确等于**下面 4 个字面量的名字。
 * 任何其它用户自定义名（含恰好含这 4 个字但不完全相同的）一律不转换，
 * 原样显示 —— 宁可漏翻，不误判。
 *
 * <p><b>这张表的中文为什么放在这里</b>：它不是"界面文案"，而是**历史数据的
 * 键值对照**（读老数据时用）。放在 {@code webapp/src/i18n/} 下是为了
 * 与语言包同域；扫描器 {@code scripts/scan-i18n.py} 对本目录整体豁免
 * （理由见该脚本的 EXCLUDE 表），因为这里的字面量是**数据键**而不是待翻译文案。
 */

