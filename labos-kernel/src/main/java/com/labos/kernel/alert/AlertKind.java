package com.labos.kernel.alert;

/**
 * 告警事件的三种形态。
 *
 * <p>这是"既不漏报、又不刷屏"的关键：单条错误不重复发，
 * 但通过首报 / 升级 / 摘要三个节点，保证人始终知道发生了什么。
 */
public enum AlertKind {

    /** 窗口内首条：立即通知，保证第一时间知道。 */
    OPENED,

    /** 计数跨过阈值（如 10 / 100 / 1000）：告诉你"这事很严重"。 */
    ESCALATED,

    /** 窗口结束：补一条摘要，告诉你"这一段时间总共多少次"。 */
    SUMMARY
}
