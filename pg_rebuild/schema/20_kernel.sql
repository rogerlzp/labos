COMMENT ON TABLE workflow_variable IS '流程级变量（作用域：流程；实验级见 experiment_variable）';


CREATE TABLE IF NOT EXISTS workflow_edge (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
