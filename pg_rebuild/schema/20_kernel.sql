  created_by     bigint,
  CONSTRAINT uk_schedule_plan UNIQUE (tenant_id, plan_no)
);
COMMENT ON TABLE schedule_plan IS
  '调度方案。★ input_snapshot 让每次调度可回放——这是"调度器是纯函数"的落地物证，也是仿真的基础。';

