-- P2 阶段 D · L3 轨道分区豁免（2026-11-15）
-- 路径粒度豁免：已人工验证「该搬运路径无轨道冲突」的路径显式登记后放行；
-- 未登记且未配置分区集的路径仍 fail-closed（不做全局 fail-open）。

CREATE TABLE IF NOT EXISTS rail_zone_exemption (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT       NOT NULL,
    path_key   VARCHAR(128) NOT NULL,
    reason     TEXT,
    operator   VARCHAR(64),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE rail_zone_exemption IS
  'L3 轨道分区豁免。path_key 与 transfer_rail_zone 同口径（srcPos->dstPos / srcDev->dstDev）。';

CREATE UNIQUE INDEX IF NOT EXISTS uk_rail_zone_exemption
    ON rail_zone_exemption (tenant_id, path_key);
