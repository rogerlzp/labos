-- 设备事件表（device_event）—— 设备主动上报的事件的落地位置
--
-- 为什么需要（2026-11-15 高通量核酸提取工作站线）：
--   客户的提取仪是「分段自驱」——设备自己跑到交换点，**主动上报【等待交互】**，
--   等上位机把板换好、上位机发【继续信号】它才往下走。
--   ⇒ 上位机要等的是「一次设备事件」，不是「某个变量当前等于某值」。
--   这张表就是那条事件的落地位置：**入站端点写、等待节点读**。
--
-- 形状照 `pause_event`（事件 + outbox）：事件类型 / 目标 / 载荷 / 派发状态。
-- `pause_event` 是「中控自己产生、要通知人」；`device_event` 是「设备产生、要唤醒流程」。
--
-- 幂等：CREATE TABLE IF NOT EXISTS + CREATE INDEX IF NOT EXISTS ⇒ 连跑两次都 exit 0。

CREATE TABLE IF NOT EXISTS device_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    device_id     BIGINT,                    -- device_instance.id（可空：只按设备码上报时先留空）
    device_code   VARCHAR(64),                -- 设备码（原样保留；解析不出实例号也不丢事件）
    event_type    VARCHAR(48)  NOT NULL,      -- 例：waiting_interaction / process_done / fault
    payload       JSONB        NOT NULL DEFAULT '{}'::jsonb,   -- 事件的载荷（哪块板、哪个工位…）
    run_id        BIGINT,                    -- 能关联到哪条 run 就填（可空）
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    dispatched_at TIMESTAMPTZ,               -- 被等待节点消费掉的时间（可空 = 还没被消费）
    attempts      INT          NOT NULL DEFAULT 0,
    last_error    VARCHAR(256)
);

COMMENT ON TABLE device_event IS
  '设备主动上报的事件。等待节点（__awaitEvent）按 (设备码, 事件类型) 取 id 之后的新事件；'
  'dispatched_at 非空 = 已被某次等待消费。';

COMMENT ON COLUMN device_event.event_type IS
  '事件类型码（例：waiting_interaction=设备到交换点等上位机换板）。';
COMMENT ON COLUMN device_event.payload IS
  '事件载荷：随事件一起带回来的信息（哪块板、哪个工位、状态字…）。';
COMMENT ON COLUMN device_event.dispatched_at IS
  '被消费时间；NULL = 还没被任何等待节点取走。';

CREATE INDEX IF NOT EXISTS ix_device_event_lookup
    ON device_event (tenant_id, device_code, event_type, id);
CREATE INDEX IF NOT EXISTS ix_device_event_pending
    ON device_event (tenant_id, id) WHERE dispatched_at IS NULL;
