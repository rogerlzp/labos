-- P2 阶段 C · 设备事实（状态版本）+ 有效等待投影（2026-11-15）
-- L1（转盘）需要可查询的「事实值 + 状态版本 + 观测时间」；
-- L5（等待交互）需要「当前有效等待交互」投影，不能只翻 device_event 日志。

-- 设备事实：每个 (device, fact_type) 只保留最新一条，state_version 供最终复核防过期。
CREATE TABLE IF NOT EXISTS device_fact (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL,
    device_resource_id BIGINT       NOT NULL,
    fact_type          VARCHAR(48)  NOT NULL,
    fact_value         TEXT,
    state_version      VARCHAR(128),
    observed_at        TIMESTAMPTZ,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE device_fact IS
  '设备上报的当前事实（转盘状态等）。每个 (device, fact_type) 只留最新；state_version/observed_at 供时效与最终复核。';

CREATE UNIQUE INDEX IF NOT EXISTS uk_device_fact
    ON device_fact (tenant_id, device_resource_id, fact_type);

-- 有效等待交互投影：只认当前会话 + 当前步骤 + 未消费/未取消/未过期的等待。
CREATE TABLE IF NOT EXISTS waiting_interaction (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL,
    device_resource_id BIGINT       NOT NULL,
    device_session_id  VARCHAR(128) NOT NULL,
    workflow_step_id   VARCHAR(128),
    interaction_id     VARCHAR(128) NOT NULL,
    status             VARCHAR(16)  NOT NULL DEFAULT 'WAITING',
    state_version      VARCHAR(128),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE waiting_interaction IS
  '当前有效等待交互投影。WAITING 才有效；CONSUMED/CANCELLED/EXPIRED 均不得授权机械臂操作交换位。';

CREATE UNIQUE INDEX IF NOT EXISTS uk_waiting_interaction
    ON waiting_interaction (tenant_id, device_resource_id, device_session_id, interaction_id);
CREATE INDEX IF NOT EXISTS ix_waiting_interaction_lookup
    ON waiting_interaction (tenant_id, device_resource_id, device_session_id, workflow_step_id)
    WHERE status = 'WAITING';
