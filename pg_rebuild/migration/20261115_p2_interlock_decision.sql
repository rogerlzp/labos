-- P2 阶段 A · 互锁决策快照（2026-11-15）
-- 可重复执行。每次「允许 / 等待 / 拒绝」物理命令下发前落一条决策快照，
-- 回答「当时凭什么放行/拒绝」（事实值 + 会话/步骤 + 状态版本 + 观测/接收时间）。

CREATE TABLE IF NOT EXISTS interlock_decision (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    run_id        BIGINT,
    node_id       BIGINT,
    command_id    VARCHAR(128),
    resource_id   BIGINT,
    interlock_code VARCHAR(32)  NOT NULL,   -- L1..L5 / SCAN / PLACE / DISPATCH
    fact_type     VARCHAR(48),
    fact_value    TEXT,
    observed_at   TIMESTAMPTZ,              -- 事实在设备侧的产生时间（设备上报时带）
    received_at   TIMESTAMPTZ,              -- 中控收到事实的时间
    state_version VARCHAR(128),             -- 状态版本 / device_event_seq
    device_session_id VARCHAR(128),
    workflow_step_id  VARCHAR(128),
    interaction_id    VARCHAR(128),
    decision      VARCHAR(16) NOT NULL,     -- ALLOW / WAIT / REJECT
    reason        TEXT,
    error_code    VARCHAR(64),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE interlock_decision IS
  '互锁决策快照。只增不改；每条对应一次命令下发前的允许/等待/拒绝判定。';
COMMENT ON COLUMN interlock_decision.state_version IS
  '事实版本（设备状态版本或 device_event 序号）；最终复核时用其判断是否过期。';

CREATE INDEX IF NOT EXISTS ix_interlock_decision_run
    ON interlock_decision (tenant_id, run_id, id);
CREATE INDEX IF NOT EXISTS ix_interlock_decision_cmd
    ON interlock_decision (tenant_id, command_id);
