-- P2 阶段 C · L4 搅拌—分液配对（2026-11-15）
-- 分液器启动前必须查配对搅拌单元的状态；配对缺失/一对多无法解析时按未知处理。

CREATE TABLE IF NOT EXISTS stirrer_dispenser_pair (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            BIGINT       NOT NULL,
    stirrer_resource_id  BIGINT       NOT NULL,
    dispenser_resource_id BIGINT      NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE stirrer_dispenser_pair IS
  '搅拌单元 ↔ 分液器的安全配对。一个分液器最多配一个搅拌单元（L4 事实源）。';

-- 一个分液器只能有一个搅拌单元（一对多无法解析 = 未知，fail-closed）
CREATE UNIQUE INDEX IF NOT EXISTS uk_stirrer_pair_dispenser
    ON stirrer_dispenser_pair (tenant_id, dispenser_resource_id);
CREATE INDEX IF NOT EXISTS ix_stirrer_pair_stirrer
    ON stirrer_dispenser_pair (tenant_id, stirrer_resource_id);
