-- P2 阶段 D · L3 轨道分区互锁（2026-11-15）
-- 每分区一个互斥资源；搬运路径 → 分区集（覆盖完整运动包络）；
-- 多分区按 resource_id 升序全有或全无获取，防循环等待。
-- 未配置分区集的路径禁止自动运行（不做空集放行）。

CREATE TABLE IF NOT EXISTS rail_zone (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    zone_code   VARCHAR(64)  NOT NULL,
    resource_id BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE rail_zone IS
  '机械臂轨道分区。每个分区一个互斥资源（resource_node kind=virtual），用 DeviceLock 互斥。';

CREATE UNIQUE INDEX IF NOT EXISTS uk_rail_zone_code
    ON rail_zone (tenant_id, zone_code);
CREATE UNIQUE INDEX IF NOT EXISTS uk_rail_zone_resource
    ON rail_zone (tenant_id, resource_id);

CREATE TABLE IF NOT EXISTS transfer_rail_zone (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL,
    path_key         VARCHAR(128) NOT NULL,
    zone_resource_id BIGINT       NOT NULL,
    seq              INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE transfer_rail_zone IS
  '搬运路径（源->目标）→ 轨道分区集。path_key 形如 "srcPos->dstPos" 或 "srcDev->dstDev"。';

CREATE UNIQUE INDEX IF NOT EXISTS uk_transfer_rail_zone
    ON transfer_rail_zone (tenant_id, path_key, zone_resource_id);
CREATE INDEX IF NOT EXISTS ix_transfer_rail_zone_path
    ON transfer_rail_zone (tenant_id, path_key, seq);
