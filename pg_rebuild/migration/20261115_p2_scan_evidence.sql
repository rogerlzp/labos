-- P2 阶段 B · 位置级扫码证据（2026-11-15）
-- 机械臂每次抓板前必须有一条绑定「源位置 + 期望板号 + 实际扫码 + 观测时间」的证据；
-- 同一条扫码证据（scan_id）只能被消费一次，防止复用旧扫码放行第二次抓板。

CREATE TABLE IF NOT EXISTS position_scan_evidence (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL,
    run_id             BIGINT,
    node_id            BIGINT,
    source_position_id BIGINT       NOT NULL,
    expected_barcode   VARCHAR(64),
    scanned_barcode    VARCHAR(64),
    observed_at        TIMESTAMPTZ,
    scan_id            VARCHAR(128) NOT NULL,
    transfer_id        BIGINT,
    command_id         VARCHAR(128),
    consumed           BOOLEAN      NOT NULL DEFAULT false,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE position_scan_evidence IS
  '抓板前的位置级扫码证据。只增不改；consumed=true 表示已被某次搬运消费，不得再放行。';

-- 同一条设备扫码事件（scan_id）只能登记一次；防止重复上报/重复消费。
CREATE UNIQUE INDEX IF NOT EXISTS uk_scan_evidence_scan
    ON position_scan_evidence (tenant_id, scan_id);
CREATE INDEX IF NOT EXISTS ix_scan_evidence_pending
    ON position_scan_evidence (tenant_id, source_position_id)
    WHERE consumed = false;
